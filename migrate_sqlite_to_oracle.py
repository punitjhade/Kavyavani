"""Copy everything from sukhan.db (SQLite) into the Oracle database.

Run it ONCE, before the first time you start the website on Oracle:

    set ORACLE_DSN=localhost:1521/XEPDB1
    set ORACLE_USER=kavyavani
    set ORACLE_PASSWORD=your_password
    python migrate_sqlite_to_oracle.py

It creates the Oracle tables if needed, copies every table (keeping the same ids so
likes, comments, follows, ... still point at the right rows) and then moves the id
counters past the copied rows. Your SQLite file is only read, never changed.
Rows that break a foreign key (for example a like on a deleted poem) are skipped and listed.
"""
import os, sqlite3, sys

import db_layer

BASE = os.path.dirname(os.path.abspath(__file__))
SQLITE = os.path.join(BASE, "sukhan.db")

# parents before children (foreign keys)
ORDER = ["users", "categories", "poets", "poems", "likes", "comments", "follows", "bookmarks",
         "collections", "collection_poems", "notifications", "reports", "announcements",
         "badges", "messages", "poem_views"]


def main():
    if not db_layer.USE_ORACLE:
        sys.exit("Set ORACLE_DSN, ORACLE_USER and ORACLE_PASSWORD first (see ORACLE_SETUP.md).")
    if not os.path.exists(SQLITE):
        sys.exit(f"{SQLITE} not found.")
    force = "--force" in sys.argv

    src = sqlite3.connect(f"file:{SQLITE}?mode=ro", uri=True)
    src.row_factory = sqlite3.Row
    dst = db_layer.connect(SQLITE)
    db_layer.init_oracle(dst)

    if not force and dst.execute("SELECT COUNT(*) AS c FROM users").fetchone()["c"] > 0:
        sys.exit("The Oracle database already has users. Migrate into an empty schema "
                 "(start the website on Oracle only after this script), or use --force to try anyway.")

    summary = []
    for table in ORDER:
        have = {r["name"] for r in src.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        if table not in have:
            continue
        ora_cols = {r["column_name"].lower() for r in
                    dst.execute("SELECT column_name FROM user_tab_columns WHERE table_name=?", (table.upper(),)).fetchall()}
        rows = [dict(r) for r in src.execute(f"SELECT * FROM {table} ORDER BY id")]
        copied, skipped, retry = 0, [], []

        def insert(row):
            # leave out NULLs so the column defaults (timestamps, flags) apply
            data = {k: v for k, v in row.items() if k in ora_cols and v is not None}
            cols = ", ".join(data)
            marks = ", ".join("?" for _ in data)
            dst.execute(f"INSERT INTO {table} ({cols}) VALUES ({marks})", tuple(data.values()))

        for row in rows:
            try:
                insert(row)
                copied += 1
            except db_layer.integrity_errors() as e:
                (retry if table == "comments" else skipped).append((row["id"], str(e).splitlines()[0]))
        if table == "comments":                      # replies may point at a later comment id
            still = []
            for cid, _ in retry:
                row = next(r for r in rows if r["id"] == cid)
                try:
                    insert(row); copied += 1
                except db_layer.integrity_errors() as e:
                    still.append((cid, str(e).splitlines()[0]))
            skipped = still
        dst.commit()
        summary.append((table, len(rows), copied, skipped))

        try:                                         # new rows must get ids after the copied ones
            dst.ddl(f"ALTER TABLE {table} MODIFY (id GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE))")
        except Exception as e:
            print(f"  note: could not reset the id counter of {table}: {str(e).splitlines()[0]}")

    print(f"{'table':<18}{'in SQLite':>10}{'copied':>9}{'skipped':>9}")
    for table, n, copied, skipped in summary:
        print(f"{table:<18}{n:>10}{copied:>9}{len(skipped):>9}")
    for table, _, _, skipped in summary:
        for rid, why in skipped[:5]:
            print(f"  skipped {table} id={rid}: {why}")
    dst.close()
    print("Done. Start the website with ORACLE_* set and it will use Oracle.")


if __name__ == "__main__":
    main()
